                if not rows:
                    raise ValueError(
                        f"동서식품 상품 카탈로그 1페이지가 비었다. data 키={sorted(data)} "
                        f"paginationInfo={data.get('paginationInfo')!r} — "
                        f"응답 스키마가 바뀌었는지 확인하라")
