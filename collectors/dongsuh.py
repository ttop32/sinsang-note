def _name(row: dict) -> str:
    """`brandNm` + `prodName` 으로 상품명을 만든다.

    `prodName` 이 브랜드를 이미 달고 있을 때가 많아 그대로 붙이면 겹친다.
    브랜드명(공백 턴 것)이나 그 첫 토큰이 상품명 안에 있으면 붙이지 않는다.

    첫 토큰까지 보는 이유 — `brandNm` 이 멋부린 표기이고 `prodName` 이 한글
    표기인 쌍이 있다. 전수에서 걸린 것:
        brandNm '맥심 T.O.P.'  + prodName '맥심 티오피 바닐라 라떼'
        brandNm '스타벅스 RTD' + prodName '스타벅스 자몽허니블랙티 로우 칼로리'
    통짜로만 비교하면 "맥심 T.O.P. 맥심 티오피 바닐라 라떼" 가 된다.
    공백을 터는 이유 — brandNm '동서벌꿀' + prodName '동서 벌꿀 아카시아꿀'.

    이 규칙으로 253건 중 36건에 브랜드가 붙고, 그 결과가 보도자료 판이 뽑던
    이름과 **5/6 일치**한다(`base.make_key()` 기준). 나머지 1건은 상품명 자체가
    다르다(docstring §전환 근거 '중복' 참고).
    """
    n = " ".join((row.get("prodName") or "").split())
    b = " ".join((row.get("brandNm") or "").split())
    if not b or not n:
        return n
    flat = n.replace(" ", "")
    if b.replace(" ", "") in flat or b.split()[0] in flat:
        return n
    return f"{b} {n}"


def _is_machine(row: dict) -> bool:
    """캡슐커피 머신인가. 먹는 게 아니다.

    253건에서 세 신호(explain 의 '머신' / volume 의 '색상' / volume 에 수량 단위
    없음)가 **정확히 같은 13건**을 가리킨다. 그중 '색상' 을 주 신호로 쓴다 —
    머신은 용량 자리에 색상을 적는다는 구조적 사실이라 제일 덜 흔들린다.

    '머신' 은 보조로만, 그것도 **수량 단위가 없을 때만** 본다. 단독으로 쓰면
    "바리스타 머신 전용 캡슐" 같은 설명이 붙는 날 식품이 굿즈로 샌다.
    캡슐은 volume 이 항상 '95g (9.5g캡슐 x 10개입)' 꼴이라 수량 단위로 막힌다.

    없는 이름/설명을 지어 쳐 봤다 — **식품 10종 오탐 0건, 머신 3종 전부 잡힘.**
      ⓐ 식품인데 '머신' 이 끼는 5종 — 전부 안 걸림(volume 에 수량 단위가 있어서)
        explain "바리스타 머신 전용 캡슐"        volume "95g (9.5g캡슐 x 10개입)"
        explain "캡슐커피 머신으로 내린 맛"       volume "138.4g(8개입)"
        explain "머신 없이 즐기는 홈카페"         volume "300g"
        explain "머신 호환 캡슐"                volume "57g (5.7g캡슐 x 10개입)"
        explain "머신 세정용 캡슐"               volume "40g (8정)"
      ⓑ 식품인데 '색상'·'머신' 이 이름/설명에 끼는 5종 — volume 이 아니면 안 봄
        prodName "색상별 마카롱 세트"            volume "120g(6개입)"
        explain  "선명한 색상의 알록달록 젤리"     volume "80g"
        explain  "네 가지 색상 크림"             volume "300g"
        explain  "커피 머신에 넣는 스틱"          volume "240g(20개입)"
        explain  "머신건처럼 쏟아지는 식감"        volume "400g"
      ⓒ 진짜 머신인데 표기가 바뀌는 3종 — ①+③ 보조가 받아냄
        explain "신형 캡슐커피 머신"             volume ""                 → 굿즈 ✅
        explain "컬러 머신"                    volume "1대"               → 굿즈 ✅
        volume  "색상: 미드나잇 블루"                                      → 굿즈 ✅
    """
    vol = row.get("volume") or ""
    if "색상" in vol:
        return True
    return "머신" in (row.get("explain") or "") and not _QTY.search(vol)


def _date(s: str) -> str:
    """'2026-09-29 09:12' 또는 '2026-09-29' → '2026-09-29'. 월·일 범위를 검증한다.

    범위를 안 보면 UUID 조각(`2026/06/92`)이 날짜로 둔갑한다(다른 브랜드에서 실측).
    """
    m = re.match(r"^\s*(20\d{2})[-.](\d{1,2})[-.](\d{1,2})", s or "")
    if not m:
        return ""
    y, mo, d = (int(x) for x in m.groups())
    if not (1 <= mo <= 12 and 1 <= d <= 31):
        return ""
    return f"{y:04d}-{mo:02d}-{d:02d}"


