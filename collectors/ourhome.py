_BRAND_REQ = "아워홈"


def _text(s: str) -> str:
    """태그를 털고 엔티티를 풀고 공백을 하나로 만든다.

    ⚠️ 세미콜론 없는 `&#39`(옛 기사에 흔하다)도 html.unescape 가 풀어 준다.
    안 풀면 홑따옴표 정규식이 상품명을 못 집는다.
    """
    return " ".join(html.unescape(_TAG.sub("", s or "")).split())


def _pick(title: str) -> str:
    """보도자료 제목에서 상품명을 뽑는다. 상품을 특정 못 하면 빈 문자열.

    "젤리 2종 출시"처럼 기사 하나에 상품이 여럿이면 버린다. 억지로 '젤리 2종'을
    상품명으로 쓰지 않는다.
    """
    t = " ".join(title.split())
    # 🔴 급식·컨세션·외식매장 기사는 여기서 통째로 버린다. 소비자가 사 올 수 없다.
    #    제목 전체를 본다 — 아래 _BRAND_TOKEN 절단 전에 걸어야 헤드라인의 '급식'을 잡는다.
    if _BRAND_REQ not in t or any(w in t for w in _B2B):
        return ""
    # “…” 홍보 헤드라인 안에 에디션/라벨이 있으면 기존 제품의 패키지 기사다.
    if any(w in m.group(1) for m in _HEAD.finditer(t) for w in _REPACK_HEAD):
        return ""
    body = _HEAD.sub(" ", t)
    # 브랜드명 앞은 홍보 헤드라인이다. 뒤쪽만 본다(함정 ①).
    b = _BRAND_TOKEN.search(body)
    if b:
        body = body[b.end():]
    if any(w in body for w in _SKIP) or _MULTI.search(body):
        return ""
    # ‘A’ 테마 ‘B’ 꼴 — 마지막 두 따옴표 사이가 테마/에디션이면 B 는 기존 제품이다.
    qs = list(_SINGLE.finditer(body))
    if len(qs) >= 2 and any(w in body[qs[-2].end():qs[-1].start()] for w in _REPACK_MID):
        return ""
    verb = None
    for m in _VERB.finditer(body):
        verb = m
    if not verb or any(w in body[verb.end():] for w in _TAIL):
        return ""
    # 브랜드·매장·서비스 '론칭' 기사는 상품 기사가 아니다(함정 ③).
    if verb.group(1) == "론칭" and any(w in body for w in _LAUNCH_NOT_PRODUCT):
        return ""
    head = body[:verb.start()]
    quoted = None
    for m in _SINGLE.finditer(head):
        quoted = m
    if not quoted or any(w in head[quoted.end():] for w in _BETWEEN):
        return ""
    # 닫는 따옴표 바로 뒤가 구분자면 상품이 더 이어진다.
    if _TRAIL_SEP.match(head[quoted.end():]):
        return ""
    name = quoted.group(1).strip(" ,·∙")
    if len(name) < 2 or any(c in name for c in "·∙&?"):
        return ""
    # 따옴표 '안'이 에디션/라벨이면 기존 제품의 패키지다('핑크 에디션').
    if any(w in name for w in _REPACK_IN):
        return ""
    return name


def _date(s: str) -> str:
    """'2026-09-18' → '2026-09-18'. 월·일 범위를 검증한다.

    범위를 안 보면 UUID 조각(`2026/06/92`)이 날짜로 둔갑한다(다른 브랜드에서 실측).
    """
    m = re.match(r"^\s*(20\d{2})[-.](\d{1,2})[-.](\d{1,2})\s*$", s or "")
    if not m:
        return ""
    y, mo, d = (int(x) for x in m.groups())
    if not (1 <= mo <= 12 and 1 <= d <= 31):
        return ""
    return f"{y:04d}-{mo:02d}-{d:02d}"


def _abs(path: str) -> str:
    path = html.unescape((path or "").strip()).strip("'\"")
    if not path:
        return ""
    return path if path.startswith("http") else SITE + path


def fetch() -> list[Item]:
    items: list[Item] = []
    seen = set()
    floor = (date.today() - timedelta(days=DAYS)).isoformat()
    with base.client() as c:
        for page in range(1, MAX_PAGES + 1):
            if page > 1:
                time.sleep(DELAY)
            r = base.retry(lambda: c.get(LIST, params={"currentPage": page}))
            r.raise_for_status()
            rows = _ROW.findall(r.text)
            # 셀렉터가 어긋나면 조용히 0건이 되는 게 제일 나쁘다. 1페이지는 반드시
            # 기사가 와야 한다(아워홈 보도자료는 1,300건이 넘는 아카이브다). 안 오면 드러낸다.
            if page == 1 and not rows:
                raise ValueError(
                    f"아워홈 보도자료 1페이지가 비었다. 응답 {len(r.text)}B — "
                    f"li.bbs / span.bbs-tip / h5.bbs-tit / p.bbs-date 중 하나가 "
                    f"바뀌었는지 확인하라(bbs-tip 이 제목, bbs-tit 이 부제다)")
            if not rows:
                break

            stop = False
            for seq, img, tip, tit, raw_date in rows:
                released = _date(_text(raw_date))
                if released and released < floor:
                    stop = True
                    continue
                title = _text(tip)
                name = _pick(title)
                if not name:
                    continue
                # 부제가 설명이다. 제목과 같은 행이 있어서(수상 기사) 같으면 비운다.
                sub = _text(tit)
                it = Item(
                    brand=BRAND,
                    name=name,
                    desc=sub if sub and sub != title else "",
                    image=_abs(img),
                    released_at=released,
                    is_new=True,     # 브랜드가 '출시'라고 낸 기사다
                    url=f"{VIEW}?seq={seq}",
                )
                if it.key not in seen:
                    seen.add(it.key)
                    items.append(it)
            if stop:
                break
            if len(rows) < PAGE_SIZE:
                break
    return items
