"""분류 체계. 화면의 1단 탭·2단 칩과 유형 페이지(/c/...)가 여기서 나온다.

브랜드 레지스트리(collectors/base.py)가 주는 brand_type·brand_sub 를 화면이
쓰는 말로 옮기는 자리다. 레지스트리 쪽은 안 건드린다 — 거기까지 바꾸면
/c/CU/ 와 /b/CU/ 처럼 내용이 같은 주소가 둘 생긴다.
"""


# 1단 탭. 375px 가용폭이 343px 인데 건수 배지를 달면 4탭도 이미 352px 로 넘친다
# (건수가 2자리이던 시절 재놓은 "4개가 상한"이 3자리가 되면서 깨졌다).
# 배지를 떼면 5탭 291px 로 들어가고, 6탭은 344px 라 한 픽셀 차로 안 된다.
# 건수는 칩을 누르면 바로 아래 #cnt 가 말해주고 푸터가 총계를 적는다.
PRIMARY = [("전체", ""), ("편의점", "편의점"), ("카페", "카페"),
           ("외식", "외식"), ("식품", "식품")]

# 2단(세부). brand_sub 값이다. 화면에는 건수 많은 순으로 깔리고(아래 render),
# 이 순서는 건수가 같을 때만 쓴다. 전에는 선언 순서 그대로 깔려서 2위인
# 일식 40건이 8번째로 밀려 375px 화면 밖에 있었다.
# 건수가 많아도 뒤로 미는 것들. 외식에서 일식·한식은 '오늘 뭐 새로 나왔나' 를
# 보러 온 사람이 잘 안 고르는데 건수는 많아서 앞자리를 차지한다. 가로로 흐르는
# 줄이라 앞자리가 곧 화면 안이다.
DEMOTE = {"일식", "한식"}

# 브랜드가 쓰는 말을 우리 분류로 옮기는 표. 김밥은 분식으로 합쳤다.
SUB_ALIAS = {"김밥": "분식"}


# 편의점이 실제로 쓰는 분류 5종을 새로 넣었다. 전부 사이트가 준 이름이고
# 내가 지어낸 게 아니다 — 김밥·즉석식은 세 브랜드가 공통으로 쓰고, 디저트·
# 안주·식재료는 CU 자체 2depth 이름이다. '간편식사' 는 안 넣는다(이마트24
# 행사 섹션의 거친 1depth 라 피스타치오·스프·치킨꼬치가 한 묶음이고,
# 140건 전부 행사라 화면에 한 건도 안 오른다).
# 김밥은 분식에 합친다 — 운영자 판단. 김밥집·떡볶이집·우동집을 따로 세우면
# 각각 한두 곳이라 칩이 비고, 사람도 '분식' 하나로 떠올린다. 편의점 삼각김밥·
# 김밥도 같은 칩으로 간다(김밥은 분식이다).
SUBS = ["커피", "베이커리", "아이스크림", "빙수", "도넛",
        "즉석식", "디저트", "안주", "식재료",
        "과자", "라면", "음료", "냉동식품", "조미료",
        "햄버거", "피자", "치킨",
        "분식", "한식", "도시락", "일식", "샌드위치", "샐러드"]

# web/pages.py 가 유형 페이지(/c/...)를 만들 때 쓰는 목록. 1단+2단을 합친다.
# 유형 페이지 목록. 1단 넷 + 2단 전부.
SECTIONS = ([("전체", "")]
            + [(k, k) for k in ["편의점", "카페", "외식", "식품"]
               + list(SUBS)])


def sub_of(r: dict) -> str:
    """2단 값. 편의점만 세부 분류 대신 업체를 쓴다.

    편의점 네 곳은 한 곳 안에 도시락·라면·음료·과자가 다 들어 있어서 상품
    분류를 주지 않는다(category 가 '신상품'·'행사 상품' 같은 판매채널이다).
    그 자리에 업체를 넣으면 'CU 에 뭐 나왔나' 를 바로 고를 수 있다.

    registry 의 brand_sub 은 안 건드린다 — 거기까지 바꾸면 /c/CU/ 유형
    페이지가 생겨 /b/CU/ 와 내용이 같은 주소가 둘이 된다.
    """
    if r.get("brand_type") == "편의점":
        # 세 브랜드 사이트에서 받아온 실제 상품 분류를 쓴다(도시락·김밥·
        # 샌드위치·즉석식·과자·음료…). 전에는 category 가 '신상품'·'행사 상품'
        # 같은 판매채널이라 업체를 대신 넣었는데, 어댑터가 진짜 분류를 받아오게
        # 되면서 그럴 이유가 없어졌다. 업체별로 보는 건 푸터의 업체 링크와
        # /b/<브랜드>/ 로 된다.
        cat = SUB_ALIAS.get(r.get("category", ""), r.get("category", ""))
        return cat if cat in SUBS else ""
    return r.get("brand_sub", "")


def primary_of(r: dict) -> str:
    """대분류. 프랜차이즈는 전부 '외식' 으로 묶는다."""
    t = r.get("brand_type", "")
    if t == "프랜차이즈":
        return "외식"
    # 과자·라면·음료·냉동식품. 나머지 셋은 "어디서 파나" 축인데 이것만 "무엇인가"
    # 축이다. 신라면 툼바는 편의점에서도 마트에서도 사니 "어디서" 로는 못 넣는다.
    if t == "제조사":
        return "식품"
    return t
