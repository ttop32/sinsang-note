# 전에는 ①을 통째로 버리고 브랜드마다 우리 분류 하나(레지스트리의 brand_sub)로
# 덮었다. 편의점 넷만 예외로 category 를 봤다. 그래서 쇼핑몰형 업체가 깨졌다 —
